# shellcheck shell=bash
# Windows and terminals take the Frosted Terminal look:
# Hyprland's borders, corners, blur and glow now come from the theme's design
# tokens (`theme` writes them for default/hypr/look.lua), and Ghostty gets Geist
# Mono and the theme's translucent background.
config_home=${XDG_CONFIG_HOME:-$HOME/.config}

# Noctalia no longer writes Hyprland's colours; its last file would still
# override the new ones from the user's hyprland.lua. Only its own file goes.
old=$config_home/hypr/noctalia.lua
if [[ -f $old ]] && head -1 "$old" | grep -qx -- '-- Generated by Noctalia'; then rm -f "$old"; fi

# Ghostty: the starter config's old defaults move to the new ones; lines the
# user changed stay as they are. The theme file is included once.
ghostty=$config_home/ghostty/config
if [[ -f $ghostty ]]; then
  sed -i -E \
    -e 's/^font-family = JetBrainsMono Nerd Font$/font-family = Geist Mono/' \
    -e 's/^font-size = 11$/font-size = 10/' \
    -e 's/^window-padding-x = 10$/window-padding-x = 16/' \
    -e 's/^window-padding-y = 8$/window-padding-y = 12/' \
    "$ghostty"
  if ! grep -q '^background-opacity' "$ghostty"; then
    printf '\n# Translucent, so the wallpaper (blurred, with blur on) shows through.\nbackground-opacity = 0.55\n' >> "$ghostty"
  fi
  include="config-file = ?$DISTRO_ID-theme"
  if ! grep -qxF "$include" "$ghostty"; then
    if grep -q '^theme = noctalia$' "$ghostty"; then
      sed -i "/^theme = noctalia\$/a $include" "$ghostty"
    else
      printf '\n# The desktop theme'"'"'s terminal colours.\n%s\n' "$include" >> "$ghostty"
    fi
  fi
fi

"/usr/bin/$DISTRO_ID" theme tokens >/dev/null 2>&1 || true
